const HEBREW = /[֐-׿]/;
const clean = (s: string) => s.trim().replace(/\s+/g, ' ');

export function colorRu(raw: string | null | undefined): string {
  if (!raw) return 'не указан';
  const v = clean(raw);
  if (COLOR_RU[v]) return COLOR_RU[v];
  const base = COLOR_BASE_RU[v.split(' ')[0]];
  if (base) return base;
  return HEBREW.test(v) ? 'другой' : v;
}

export function fuelRu(raw: string | null | undefined): string {
  if (!raw) return 'не указан';
  const v = clean(raw);
  if (FUEL_RU[v]) return FUEL_RU[v];
  for (const [k, ru] of Object.entries(FUEL_RU)) if (v.includes(k)) return ru;
  return HEBREW.test(v) ? 'другое' : v;
}

export function ownershipRu(raw: string | null | undefined): string {
  if (!raw) return 'не указана';
  const v = clean(raw);
  if (OWNERSHIP_RU[v]) return OWNERSHIP_RU[v];
  for (const [k, ru] of Object.entries(OWNERSHIP_RU)) if (v.includes(k)) return ru;
  return HEBREW.test(v) ? 'другая' : v;
}

export function originRu(raw: string | null | undefined): string {
  if (!raw) return '';
  const v = clean(raw);
  if (ORIGIN_RU[v]) return ORIGIN_RU[v];
  for (const [k, ru] of Object.entries(ORIGIN_RU)) if (v.includes(k)) return ru;
  return HEBREW.test(v) ? 'другое' : v;
}
